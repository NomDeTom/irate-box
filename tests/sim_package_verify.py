"""The Box doctor's package and code check (health.py, notes: box-doctor-hardening-plan Part 1, step 1), offline:
dpkg --verify's damaged files named, conffiles kept apart and worded as edited-or-damaged, a line dpkg could not
check left out; irate-box's tree held against the updater's checkout at the installed commit; the startup packages
and their dependencies checked once after a boot, and kept for that boot's later runs. python3 tests/sim_package_verify.py"""

import hashlib
import os
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
T = Path(tempfile.mkdtemp(prefix="package-verify-"))
state, etc, code, src = T / "state", T / "etc", T / "code", T / "src"
for p in (state, etc, code, src):
    p.mkdir(parents=True)
for relative, text in (
    ("irate_box/root/health.py", "print('health')\n"),
    ("irate_box/root/housecall.py", "print('housecall')\n"),
    ("install.sh", "#!/bin/bash\n"),
):
    path = code / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
(code / "VERSION").write_text("abc1234 (installed 2026-10-28)\n")
os.environ.update(
    HUB_STATE_DIR=str(state),
    HUB_ETC_DIR=str(etc),
    HUB_CODE_DIR=str(code),
    HUB_UPDATE_DIR=str(src),
    HUB_BOOT_ID="boot-one",
)
sys.path.insert(0, str(REPO))
from irate_box.finding import message_ids
from irate_box.root import health

fails = 0


def check(name, cond, info=""):
    global fails
    print(("PASS " if cond else "FAIL ") + name + ("" if cond else f"  {info!r}"))
    fails += not cond


def blob(path):
    sha = hashlib.sha1(usedforsecurity=False)
    sha.update(f"blob {path.stat().st_size}\0".encode())
    sha.update(path.read_bytes())
    return sha.hexdigest()


COMMIT = "a" * 40
# The installed commit's tree, as the updater's checkout has it: the files as they were installed, not as they are now.
TREE = {
    path.relative_to(code).as_posix(): blob(path)
    for path in sorted(p for p in code.rglob("*") if p.is_file() and p.name != "VERSION")
}
DEPS = "\n".join(
    (
        "systemd\t\tlibc6, libudev1",
        "libc6\t\t",
        "libudev1\t\t",
        "nginx\t\tlibc6, openssl",
        "openssl\t\t",
        "python3\t\tlibc6",
        "dpkg\t\t",
        "apt\t\tlibc6",
        "unrelated\t\t",
    )
)
verify = {"full": "", "startup": ""}
calls = []


def fake_run(*cmd, **kw):
    calls.append(cmd)
    if cmd[0] == "dpkg-query":
        return type("R", (), {"returncode": 0, "stdout": DEPS, "stderr": ""})()
    if cmd[0] == "dpkg" and cmd[1] == "--verify":
        return type("R", (), {"returncode": 0, "stdout": verify["startup" if len(cmd) > 2 else "full"], "stderr": ""})()
    if cmd[0] == "git" and "rev-parse" in cmd:
        return type("R", (), {"returncode": 0, "stdout": COMMIT + "\n", "stderr": ""})()
    if cmd[0] == "git" and "ls-tree" in cmd:
        entries = [f"100644 blob {sha}\t{relative}" for relative, sha in TREE.items()]
        return type("R", (), {"returncode": 0, "stdout": "\0".join(entries) + "\0", "stderr": ""})()
    return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()


health.run = fake_run
verify_before = list(calls)

check(
    "the startup packages and their dependencies, from dpkg's Depends",
    health.startup_packages() == ["apt", "dpkg", "libc6", "libudev1", "nginx", "openssl", "python3", "systemd"],
    health.startup_packages(),
)

changed_file = T / "changed-package-file"
changed_file.write_text("generated by the board\n")
ff_file = T / "ff-package-file"
ff_file.write_bytes(b"\xff" * 64)
verify["full"] = (
    "??5??????   /usr/bin/broken\n"
    f"??5??????   {changed_file}\n"
    f"??5??????   {ff_file}\n"
    "??5?????? c /etc/broken.conf\n"
    "????????? c /etc/unreadable\n"
    "missing    /usr/bin/gone\n"
)
found = {f["id"]: f for f in health.check_package_files(quick=False)}
check(
    "a package file that reads back as 0xFF: a problem naming it, and only that",
    found["package-files"]["status"] == "problem"
    and found["package-files"]["evidence"] == [str(ff_file)]
    and "packages.damaged" in message_ids(found["package-files"]),
    found.get("package-files"),
)
check(
    "a package file that changed, was removed or cannot be read: a warning, not the card's 0xFF",
    found["package-changed"]["status"] == "warn"
    and set(found["package-changed"]["evidence"]) == {str(changed_file), "/usr/bin/broken", "/usr/bin/gone"}
    and "packages.changed" in message_ids(found["package-changed"]),
    found.get("package-changed"),
)
check(
    "a conffile whose checksum differs: a warning, edited or damaged",
    found["package-conffiles"]["status"] == "warn"
    and found["package-conffiles"]["evidence"] == ["/etc/broken.conf"]
    and "conffiles.changed" in message_ids(found["package-conffiles"]),
    found.get("package-conffiles"),
)
check(
    "a line dpkg could not check (all ?): not damage",
    all("/etc/unreadable" not in e for f in found.values() for e in f["evidence"]),
    found,
)
check(
    "the tree matches the installed commit: fine",
    found["irate-box-tree"]["status"] == "ok" and "package-tree.ok" in message_ids(found["irate-box-tree"]),
    found.get("irate-box-tree"),
)

verify["full"] = ""
found = {f["id"]: f for f in health.check_package_files(quick=False)}
check(
    "clean package files: fine, and no conffile finding",
    found["package-files"]["status"] == "ok"
    and "package-conffiles" not in found
    and found["irate-box-tree"]["status"] == "ok",
    found,
)

(code / "irate_box/root/health.py").write_text("print('tampered')\n")
found = {f["id"]: f for f in health.check_package_files(quick=False)}
check(
    "a file of irate-box's tree differing from the installed commit: a problem naming it",
    found["irate-box-tree"]["status"] == "problem"
    and found["irate-box-tree"]["evidence"] == ["irate_box/root/health.py"]
    and "package-tree.damaged" in message_ids(found["irate-box-tree"]),
    found.get("irate-box-tree"),
)
(code / "irate_box/root/health.py").write_text("print('health')\n")
(code / "irate_box/root/housecall.py").unlink()
found = {f["id"]: f for f in health.check_package_files(quick=False)}
check(
    "a file of irate-box's tree missing: a problem naming it",
    found["irate-box-tree"]["status"] == "problem"
    and found["irate-box-tree"]["evidence"] == ["irate_box/root/housecall.py (missing)"],
    found.get("irate-box-tree"),
)
(code / "irate_box/root/housecall.py").write_text("print('housecall')\n")

verify["startup"] = ""
calls.clear()
os.environ["HUB_BOOT_ID"] = "boot-a"
first = health.check_package_files(quick=True)
quick_calls = list(calls)
check(
    "a quick run after a boot checks the startup packages alone",
    quick_calls and quick_calls[0][0] == "dpkg-query" and any(c[0] == "dpkg" and len(c) > 2 for c in quick_calls),
    quick_calls,
)
check(
    "  and keeps its answer for this boot's later runs",
    "package-check.json" in os.listdir(state / "control")
    and health.check_package_files(quick=True) == first
    and len(calls) == len(quick_calls),
    (state / "control" / "package-check.json").read_text(),
)
os.environ["HUB_BOOT_ID"] = "boot-b"
calls.clear()
health.check_package_files(quick=True)
check(
    "  the next boot checks the startup packages again",
    any(c[0] == "dpkg" and len(c) > 2 for c in calls),
    calls,
)

verify["startup"] = f"??5??????   {ff_file}\n"
os.environ["HUB_BOOT_ID"] = "boot-c"
found = health.check_package_files(quick=True)
check(
    "a damaged startup package file: a problem naming it",
    found and found[0]["id"] == "package-files" and str(ff_file) in found[0]["evidence"],
    found,
)

source = (REPO / "irate_box/root/health.py").read_text()
scan = source[source.index("def scan(quick=False):") : source.index("def _previous_report")]
check(
    "the scan runs the check, in both the weekly and the quick run",
    "check_package_files" in scan and "check in (check_kiwix, check_builds, check_package_files)" in scan,
    scan[:400],
)

print("ok" if not fails else f"{fails} failure(s)")
sys.exit(1 if fails else 0)
